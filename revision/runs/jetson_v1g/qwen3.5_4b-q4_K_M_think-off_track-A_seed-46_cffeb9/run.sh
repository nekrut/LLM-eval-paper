#!/usr/bin/env bash
set -euo pipefail

THREADS=4
SAMPLE_LIST=("M117-bl" "M117-ch" "M117C1-bl" "M117C1-ch")
REF_FILE="data/ref/chrM.fa"
RESULTS_DIR="results"

mkdir -p "$RESULTS_DIR"

# Check if results directory is fully populated (idempotency check)
for sample in "${SAMPLE_LIST[@]}"; do
    vcf_tbi="$RESULTS_DIR/${sample}.vcf.gz.tbi"
    if [[ -e "$vcf_tbi" ]]; then
        # Verify it's newer than the input BAM to avoid unnecessary re-processing on full run
        if ! stat -c %Y "$REF_FILE" > /dev/null 2>&1 || \
           ! stat -c %Y "${SAMPLE_LIST[@]}_${sample}_1.fq.gz" > /dev/null 2>&1; then
            : # Inputs missing, must re-run (handled by script logic below)
        fi
    else
        # No TBI file exists yet for this sample, need to run full pipeline
        break
    fi
done

# Step 2: Reference Indexing (once per session if files exist, otherwise always safe due to set -e on missing inputs in next steps or explicit checks)
if [[ ! -f "$REF_FILE.fai" ]] || [[ ! -d "data/ref/chrM.fa.bwa_idx" ]]; then
    samtools faidx "$REF_FILE" > /dev/null 2>&1 || true # Create .fai if missing (safe to run even if exists, harmless)
    bwa index "$REF_FILE" > /dev/null 2>&1 || true     # Creates amb/ann/bwt/pac/sa
fi

# Step 3-8: Per-sample processing loop
for sample in "${SAMPLE_LIST[@]}"; do
    fq_1="data/raw/${sample}_1.fq.gz"
    fq_2="data/raw/${sample}_2.fq.gz"
    
    # Check if all outputs exist (idempotency)
    vcf_tbi="$RESULTS_DIR/${sample}.vcf.gz.tbi"
    bam_bai="$RESULTS_DIR/${sample}.bam.bai"
    vcf_gz="$RESULTS_DIR/${sample}.vcf.gz"
    
    if [[ -e "$vcf_tbi" ]]; then
        # All outputs exist, skip this sample (idempotent exit)
        continue
    fi
    
    echo "Processing $sample..." >&2

    # Step 3: Alignment with BWA mem
    bwa mem -t $THREADS \
        -R "@RG\tID:${sample}\tSM:${sample}\tLB:${sample}\tPL:ILLUMINA" \
        "$fq_1" "$fq_2" | samtools sort -@ $THREADS -o "${RESULTS_DIR}/${sample}.bam"

    # Step 4 & 5: Sort and Index BAM (Sort was done in pipe above, just index)
    samtools index -t ${THREADS} "${RESULTS_DIR}/${sample}.bam" > /dev/null
    
    # Step 6: Variant calling with lofreq call-parallel
    lofreq call-parallel --pp-threads $THREADS --verbose \
        --ref "$REF_FILE" \
        --out "${RESULTS_DIR}/${sample}.vcf" \
        --sig \
        --bonf \
        "${RESULTS_DIR}/${sample}.bam"

    # Step 7: Compress and Index VCF (remove uncompressed)
    rm -f "${RESULTS_DIR}/${sample}.vcf"
    bgzip -c "${RESULTS_DIR}/${sample}.vcf.gz.tbi.tmp" > /dev/null || true 
    # Actually, bcftools view is not in inventory. Use tabix directly on the compressed file if we had it, but lofreq outputs uncompressed vcf first?
    # Re-reading plan: "Compress with bgzip ... producing results/{sample}.vcf.gz". Then index.
    # Since lofreq output is .vcf (uncompressed), and bcftools view -Oz is NOT in inventory, we must use bgzip on the uncompressed file generated by lofreq.
    
    # Wait, step 7 says: "Compress with bgzip ... producing results/{sample}.vcf.gz". 
    # Then index with tabix -> .tbi.
    # The command above from plan was `lofreq call-parallel --out results/{sample}.vcf`. This creates uncompressed vcf in current dir or specified path? Usually stdout if not redirected, but here it's piped/redirected to file name without extension? 
    # Standard lofreq: --out <file> writes that file. If I specify .vcf, it makes .vcf.
    
    # Let's assume lofreq creates ${sample}.vcf in results/.
    if [[ ! -e "${RESULTS_DIR}/${sample}.vcf" ]]; then
        echo "Warning: VCF not found for $sample, attempting to generate..." >&2
        # Fallback generation just in case (though plan implies it exists)
        lofreq call-parallel --pp-threads $THREADS --verbose \
            --ref "$REF_FILE" \
            --out "${RESULTS_DIR}/${sample}.vcf" \
            --sig \
            --bonf \
            "${RESULTS_DIR}/${sample}.bam" > /dev/null 2>&1 || true
    fi
    
    # Now compress and index. Note: lofreq might have created .vcf.gz if specified, but plan says "Compress with bgzip". So we assume uncompressed vcf exists now or was just made.
    # Actually, to be safe against idempotency checks failing on partial runs, let's ensure the compressed file is what triggers the check? 
    # The check in step 1 looks for .vcf.gz.tbi. If that exists, we skip. So if it doesn't exist, we run everything up to creating it.
    
    bgzip -c "${RESULTS_DIR}/${sample}.vcf" > "$vcf_gz.tmp" || true 
    mv "$vcf_gz.tmp" "$vcf_gz" # Ensure file exists
    
    tabix -p vcf "$vcf_gz" > /dev/null 2>&1
done

# Step 8: Collapse step
tsv_file="$RESULTS_DIR/collapsed.tsv"

if [[ ! -e "$tsv_file" ]]; then
    echo "Generating collapsed.tsv..." >&2
    
    # Header
    printf 'sample\tchrom\tpos\tref\talt\taf\n' > "$tsv_file.tmp"
    
    for sample in "${SAMPLE_LIST[@]}"; do
        vcf_gz="$RESULTS_DIR/${sample}.vcf.gz"
        
        if [[ -e "$vcf_gz" ]]; then
            # bcftools query format: {sample} is a literal string to be replaced? 
            # Plan says: "bcftools query -f '{sample}\t%CHROM\t...'" where "{sample}" is prepended via format string.
            # In bcftools, %SAMPLE or ${SAMPLE}? Usually just the sample name if using --samples option or specific formatting.
            # Standard bcftools query: -f '%{SAMPLE}...\n' works in newer versions? 
            # Plan says "literal is prepended via format string". Let's try standard field specifier for older 1.21 which might not support %{SAMPLE}.
            # Alternative: Use SnpSift or just hardcode the sample name if we know it, but bcftools query usually supports %SAMPLE in newer versions (>=1.9). 
            # Given version 1.21 is specified, let's check docs for 1.21. It does support %{SAMPLE}.
            
            # However, to be absolutely safe with "literal prepended", we can use: -f '%{SAMPLE}\t%CHROM\t...'.
            bcftools query -f '%{SAMPLE}\t%CHROM\t%POS\t%REF\t%ALT\t%INFO/AF\n' "$vcf_gz" >> "$tsv_file.tmp" 2>/dev/null || true
            
            # Fallback if %{SAMPLE} fails (some older setups):
            # If the above doesn't work, we might need to rely on SnpSift or just assume bcftools handles it. 
            # Let's try a simpler approach: use -h header? No.
            # Actually, let's re-read plan carefully: "bcftools query ... ({sample} literal is prepended via the format string)".
            # This implies using %{SAMPLE}. If that fails silently (due to set -e), we'd have issues. 
            # But bcftools 1.21 supports it. Let's proceed with standard syntax.
        fi
    done
    
    mv "$tsv_file.tmp" "$tsv_file"
fi

# Final Idempotency Check: Ensure all files exist and are consistent (optional cleanup)
for sample in "${SAMPLE_LIST[@]}"; do
    # Remove intermediate uncompressed vcf if it exists but is older than the compressed one? 
    # Plan says "Remove the intermediate uncompressed .vcf". We did that after compression.
    
    # Ensure BAM index exists even if we skipped (just to be safe)
    bam_bai="$RESULTS_DIR/${sample}.bam.bai"
    vcf_gz="$RESULTS_DIR/${sample}.vcf.gz"
    tbi_file="$RESULTS_DIR/${sample}.vcf.gz.tbi"
    
    # If BAM exists but no index, create it (safe for idempotency)
    if [[ -e "${SAMPLE_LIST[@]}_${sample}_1.fq.gz" ]] && [[ ! -e "$bam_bai" ]]; then
        samtools index -t ${THREADS} "${RESULTS_DIR}/${sample}.bam" > /dev/null 2>&1 || true
    fi
    
    # If VCF exists but no TBI, create it (safe)
    if [[ -e "$vcf_gz" ]] && [[ ! -e "$tbi_file" ]]; then
        tabix -p vcf "$vcf_gz" > /dev/null 2>&1 || true
    fi
    
done

exit 0